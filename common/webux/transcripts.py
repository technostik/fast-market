from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

#: Sidecars the publish pipelines write next to ``clip.mp4``.
SIDECAR_SUFFIXES = ("_transcript.txt", ".transcript.txt")

#: Text stored by the pipelines when no transcript could be produced.
_PLACEHOLDER_PREFIXES = ("(transcript unavailable)", "(no transcript")


@dataclass(frozen=True)
class Transcript:
    """A transcript found for a video.

    ``path`` is the on-disk file holding the text whenever one exists. It is
    empty when the text only lived in the meta log and ``materialize`` was
    False (callers that need to feed the text to another CLI materialize it).
    ``origin`` says where it came from: ``meta-txt``, ``meta-ass``,
    ``meta-text`` or ``sidecar``.
    """

    path: Path
    text: str
    origin: str


def is_placeholder(text: str) -> bool:
    """True for the sentinel strings the pipelines store when transcription failed."""
    value = (text or "").strip()
    return any(value.startswith(prefix) for prefix in _PLACEHOLDER_PREFIXES)


def ass_to_plain_text(ass_path: str | Path) -> str:
    """Extract the spoken dialogue lines of an ASS subtitle file."""
    lines = []
    with open(ass_path, encoding="utf-8") as f:
        for line in f:
            if not line.startswith("Dialogue:"):
                continue
            parts = line.split(",", 9)
            if len(parts) < 10:
                continue
            text = re.sub(r"\{[^}]*\}", "", parts[9].strip())
            if text:
                lines.append(text)
    return "\n".join(lines)


def _read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8").strip()
    except OSError:
        return ""


def find_transcript(
    video: str | Path,
    files: dict | None = None,
    transcript_text: str = "",
    *,
    materialize: bool = True,
) -> Transcript | None:
    """Reuse a transcript already produced for ``video`` instead of re-transcribing.

    Lookup order (first real, non-placeholder hit wins):

    1. ``files["transcript_txt"]`` recorded in a ``*-long-meta.json``;
    2. ``files["transcript"]`` (ASS) — converted to plain text, and written to
       ``<stem>_transcript.txt`` when ``materialize`` is on and it is missing;
    3. the sidecars ``<stem>_transcript.txt`` and ``<stem>.transcript.txt``;
    4. ``transcript_text`` stored in the meta log itself.

    Long-publish and short-publish both write ``<stem>_transcript.txt``, so
    this covers "one generated by long_publish before" as well.
    """
    video = Path(video).expanduser()
    files = files if isinstance(files, dict) else {}

    recorded = str(files.get("transcript_txt") or "").strip()
    if recorded:
        path = Path(recorded).expanduser()
        if path.is_file():
            text = _read_text(path)
            if text and not is_placeholder(text):
                return Transcript(path, text, "meta-txt")

    ass = str(files.get("transcript") or "").strip()
    if ass:
        ass_path = Path(ass).expanduser()
        if ass_path.is_file():
            text = ass_to_plain_text(ass_path).strip()
            if text and not is_placeholder(text):
                txt = video.parent / f"{video.stem}_transcript.txt"
                if materialize and not txt.exists():
                    txt.write_text(text, encoding="utf-8")
                return Transcript(txt if materialize else Path(""), text, "meta-ass")

    for suffix in SIDECAR_SUFFIXES:
        path = video.parent / f"{video.stem}{suffix}"
        if path.is_file():
            text = _read_text(path)
            if text and not is_placeholder(text):
                return Transcript(path, text, "sidecar")

    stored = str(transcript_text or "").strip()
    if stored and not is_placeholder(stored):
        path = video.parent / f"{video.stem}_transcript.txt"
        if materialize and not path.exists():
            path.write_text(stored, encoding="utf-8")
        return Transcript(path if materialize else Path(""), stored, "meta-text")

    return None
